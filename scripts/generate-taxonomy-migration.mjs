#!/usr/bin/env node

/**
 * Generate a SQL migration that loads Competency, Market, and Standards taxonomies
 * from the three CSV files. Competency goes into competency_taxonomy_seed (read-only),
 * then is synced to company_capabilities_ref. Run once, then commit the generated migration.
 *
 * Usage:
 *   node scripts/generate-taxonomy-migration.mjs [competency.csv] [market.csv] [standards.csv]
 * Paths default to supabase/seed-data/ if omitted.
 *
 * Requires: migration 20260216990000_create_competency_taxonomy_seed.sql (creates the seed table).
 * Output: supabase/migrations/20260217000000_seed_taxonomies_from_csv.sql
 */

import { readFileSync, existsSync, writeFileSync } from "fs";
import { resolve, dirname } from "path";
import { fileURLToPath } from "url";
import { createHash } from "crypto";

const __dirname = dirname(fileURLToPath(import.meta.url));
const projectRoot = resolve(__dirname, "..");

function parseCsvLine(line) {
  const out = [];
  let i = 0;
  while (i < line.length) {
    if (line[i] === '"') {
      let end = i + 1;
      while (end < line.length) {
        const next = line.indexOf('"', end);
        if (next === -1) break;
        if (line[next + 1] === '"') {
          end = next + 2;
          continue;
        }
        end = next;
        break;
      }
      out.push(
        line
          .slice(i + 1, end)
          .replace(/""/g, '"')
          .trim(),
      );
      i = end + 1;
      if (line[i] === ",") i++;
      continue;
    }
    const comma = line.indexOf(",", i);
    const value =
      comma === -1 ? line.slice(i).trim() : line.slice(i, comma).trim();
    out.push(value);
    i = comma === -1 ? line.length : comma + 1;
  }
  return out;
}

function readCsv(filePath) {
  if (!existsSync(filePath)) {
    console.warn("File not found:", filePath);
    return [];
  }
  const text = readFileSync(filePath, "utf8");
  const lines = text.split(/\r?\n/).filter((l) => l.trim());
  const [header, ...rows] = lines;
  const cols = parseCsvLine(header);
  return rows.map((row) => {
    const values = parseCsvLine(row);
    const obj = {};
    cols.forEach((c, i) => {
      obj[c] = values[i] ?? "";
    });
    return obj;
  });
}

function sqlEscape(s) {
  if (s == null || s === "") return "NULL";
  return "'" + String(s).replace(/'/g, "''") + "'";
}

function deterministicUuid(name, salt = "") {
  const h = createHash("sha256").update(salt + name).digest("hex");
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-4${h.slice(13, 16)}-a${h.slice(17, 20)}-${h.slice(20, 32)}`;
}

const seedDataDir = resolve(projectRoot, "supabase", "seed-data");
const args = process.argv.slice(2);
const competencyPath =
  args[0] || resolve(seedDataDir, "Competency Taxonomy(in).csv");
const marketPath =
  args[1] || resolve(seedDataDir, "Market list(Market list v2).csv");
const standardsPath =
  args[2] || resolve(seedDataDir, "standard taxonomy(in).csv");

const competencyRows = readCsv(competencyPath);
const marketRows = readCsv(marketPath);
const standardsRows = readCsv(standardsPath);

if (marketRows.length === 0 && standardsRows.length === 0 && competencyRows.length === 0) {
  console.error("No CSV data found. Put CSV files in supabase/seed-data/ or pass paths.");
  process.exit(1);
}

const out = [];

out.push("-- Seed Competency, Market, and Standards taxonomies from CSV data.");
out.push("-- Generated by scripts/generate-taxonomy-migration.mjs");
out.push("-- Run after 20260216200000_add_parent_id_to_capabilities_ref.");
out.push("");

// ---- Markets ----
const mL1Key = "Market_Level_1";
const mL2Key = "Market_Level_2";
const marketL1 = new Map();
const marketL2 = new Set();
const marketL1Order = [];

for (const row of marketRows) {
  const n1 = (row[mL1Key] ?? "").trim();
  const n2 = (row[mL2Key] ?? "").trim();
  if (!n1) continue;
  if (!marketL1.has(n1)) {
    marketL1.set(n1, deterministicUuid("market-l1-" + n1));
    marketL1Order.push(n1);
  }
  if (!n2) continue;
  const pid = marketL1.get(n1);
  const key = `${pid}|${n2}`;
  if (marketL2.has(key)) continue;
  marketL2.add(key);
}

out.push("-- Markets: clear and insert L1 then L2");
out.push("DELETE FROM public.company_markets;");
out.push("DELETE FROM public.markets;");
out.push("");

for (const n1 of marketL1Order) {
  const id = marketL1.get(n1);
  out.push(`INSERT INTO public.markets (id, name, parent_id, sort_order) VALUES (${sqlEscape(id)}, ${sqlEscape(n1)}, NULL, 0);`);
}

for (const row of marketRows) {
  const n1 = (row[mL1Key] ?? "").trim();
  const n2 = (row[mL2Key] ?? "").trim();
  if (!n1 || !n2) continue;
  const pid = marketL1.get(n1);
  const key = `${pid}|${n2}`;
  if (marketL2.has(key)) {
    marketL2.delete(key);
    const id = deterministicUuid("market-l2-" + key);
    out.push(`INSERT INTO public.markets (id, name, parent_id, sort_order) VALUES (${sqlEscape(id)}, ${sqlEscape(n2)}, ${sqlEscape(pid)}, 0);`);
  }
}
out.push("");

// ---- Standards ----
const sIndKey = "Industry";
const sStdKey = "Standard";
const stdL1 = new Map();
const stdL2 = new Set();
const stdL1Order = [];

for (const row of standardsRows) {
  const ind = (row[sIndKey] ?? "").trim();
  const std = (row[sStdKey] ?? "").trim();
  if (!ind) continue;
  if (!stdL1.has(ind)) {
    stdL1.set(ind, deterministicUuid("std-l1-" + ind));
    stdL1Order.push(ind);
  }
  if (!std) continue;
  const pid = stdL1.get(ind);
  const key = `${pid}|${std}`;
  if (stdL2.has(key)) continue;
  stdL2.add(key);
}

out.push("-- Standards: clear and insert L1 then L2");
out.push("DELETE FROM public.company_standards;");
out.push("DELETE FROM public.standards_ref;");
out.push("");

for (const ind of stdL1Order) {
  const id = stdL1.get(ind);
  out.push(`INSERT INTO public.standards_ref (id, name, parent_id, sort_order) VALUES (${sqlEscape(id)}, ${sqlEscape(ind)}, NULL, 0);`);
}

const stdL2Done = new Set();
for (const row of standardsRows) {
  const ind = (row[sIndKey] ?? "").trim();
  const std = (row[sStdKey] ?? "").trim();
  if (!ind || !std) continue;
  const pid = stdL1.get(ind);
  const key = `${pid}|${std}`;
  if (!stdL2Done.has(key)) {
    stdL2Done.add(key);
    const id = deterministicUuid("std-l2-" + key);
    out.push(`INSERT INTO public.standards_ref (id, name, parent_id, sort_order) VALUES (${sqlEscape(id)}, ${sqlEscape(std)}, ${sqlEscape(pid)}, 0);`);
  }
}
out.push("");

// ---- Competency (L1, L2, L3) - no delete, only insert ----
const cL1Key = "Level 1 - Domain";
const cL2Key = "Level 2 - Capability Group";
const cL3Key = "Level 3 - Specific Competency";
const capL1 = new Map();
const capL2 = new Map();
const capL3 = new Set();
const capL1Order = [];

for (const row of competencyRows) {
  const n1 = (row[cL1Key] ?? "").trim();
  const n2 = (row[cL2Key] ?? "").trim();
  const n3 = (row[cL3Key] ?? "").trim();
  if (!n1) continue;
  if (!capL1.has(n1)) {
    capL1.set(n1, deterministicUuid("cap-l1-" + n1));
    capL1Order.push(n1);
  }
  if (!n2) continue;
  const p1 = capL1.get(n1);
  const k2 = `${p1}|${n2}`;
  if (!capL2.has(k2)) capL2.set(k2, deterministicUuid("cap-l2-" + k2));
  if (!n3) continue;
  const p2 = capL2.get(k2);
  const k3 = `${p2}|${n3}`;
  capL3.add(JSON.stringify([p2, n3]));
}

out.push("-- Competency: replace seed table (read-only canonical), then sync to company_capabilities_ref");
out.push("DELETE FROM public.competency_taxonomy_seed;");
out.push("");
for (const n1 of capL1Order) {
  const id = capL1.get(n1);
  out.push(`INSERT INTO public.competency_taxonomy_seed (id, name, category, parent_id, is_active) VALUES (${sqlEscape(id)}, ${sqlEscape(n1)}, ${sqlEscape(n1)}, NULL, true);`);
}
for (const row of competencyRows) {
  const n1 = (row[cL1Key] ?? "").trim();
  const n2 = (row[cL2Key] ?? "").trim();
  if (!n1 || !n2) continue;
  const p1 = capL1.get(n1);
  const k2 = `${p1}|${n2}`;
  const id2 = capL2.get(k2);
  if (!id2) continue;
  out.push(`INSERT INTO public.competency_taxonomy_seed (id, name, category, parent_id, is_active) VALUES (${sqlEscape(id2)}, ${sqlEscape(n2)}, ${sqlEscape(n1)}, ${sqlEscape(p1)}, true);`);
}
const capL3Done = new Set();
for (const row of competencyRows) {
  const n2 = (row[cL2Key] ?? "").trim();
  const n3 = (row[cL3Key] ?? "").trim();
  if (!n2 || !n3) continue;
  const p1 = capL1.get((row[cL1Key] ?? "").trim());
  const k2 = `${p1}|${n2}`;
  const p2 = capL2.get(k2);
  if (!p2) continue;
  const key = p2 + "\x00" + n3;
  if (capL3Done.has(key)) continue;
  capL3Done.add(key);
  const id3 = deterministicUuid("cap-l3-" + key);
  out.push(`INSERT INTO public.competency_taxonomy_seed (id, name, category, parent_id, is_active) VALUES (${sqlEscape(id3)}, ${sqlEscape(n3)}, NULL, ${sqlEscape(p2)}, true);`);
}
out.push("");
out.push("-- Sync seed into editable ref table (so app starts with CSV taxonomy)");
out.push("INSERT INTO public.company_capabilities_ref (id, name, category, parent_id, is_active)");
out.push("SELECT id, name, category, parent_id, is_active FROM public.competency_taxonomy_seed");
out.push("ON CONFLICT (id) DO UPDATE SET name = EXCLUDED.name, category = EXCLUDED.category, parent_id = EXCLUDED.parent_id, is_active = EXCLUDED.is_active;");
out.push("");

const migrationPath = resolve(
  projectRoot,
  "supabase",
  "migrations",
  "20260217000000_seed_taxonomies_from_csv.sql",
);
writeFileSync(migrationPath, out.join("\n") + "\n", "utf8");
console.log("Wrote", migrationPath);
console.log("Markets L1:", marketL1.size, "L2:", marketL2.size);
console.log("Standards L1:", stdL1.size, "L2:", stdL2Done.size);
console.log("Competency L1:", capL1.size, "L2:", capL2.size, "L3:", capL3Done.size);

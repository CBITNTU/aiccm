#!/usr/bin/env node
/**
 * Generate the bilingual reference-taxonomy seed SQL from the source CSVs in
 * docs/taxonomy_cn/ (English + Simplified-Chinese columns side by side).
 *
 * Regenerates, in place:
 *   drizzle/seed/010_seed_competency_taxonomy.sql
 *   drizzle/seed/020_seed_markets.sql
 *   drizzle/seed/030_seed_standards.sql
 *
 * Each row carries both `name` (English) and `name_zh` (Chinese); the competency
 * rows also carry `category` / `category_zh`. Row IDs are deterministic UUIDv5
 * keyed on the English name path, so unchanged rows keep stable IDs across future
 * CSV revisions (only genuinely new/changed rows churn) — which keeps company
 * selections that reference them intact.
 *
 * Run:  node scripts/generate-taxonomy-seeds.mjs
 * After running, apply with:  npm run db:seed-ref   (or the reseed-with-remap script)
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { v5 as uuidv5 } from "uuid";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, "..");
const CSV_DIR = join(ROOT, "docs", "taxonomy_cn");
const SEED_DIR = join(ROOT, "drizzle", "seed");

// Fixed namespace so UUIDv5 output is stable across machines and runs.
const NAMESPACE = "b2f6c0de-7a1e-4c2b-9f3a-1d5e6a7b8c90";
const id = (key) => uuidv5(key, NAMESPACE);

// ---------------------------------------------------------------------------
// Minimal RFC-4180 CSV parser: handles quoted fields, embedded commas/newlines,
// escaped quotes ("") and a UTF-8 BOM on the first field. Returns array of
// objects keyed by the header row.
// ---------------------------------------------------------------------------
function parseCsv(text) {
  const rows = [];
  let field = "";
  let record = [];
  let inQuotes = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (inQuotes) {
      if (c === '"') {
        if (text[i + 1] === '"') {
          field += '"';
          i++;
        } else {
          inQuotes = false;
        }
      } else {
        field += c;
      }
    } else if (c === '"') {
      inQuotes = true;
    } else if (c === ",") {
      record.push(field);
      field = "";
    } else if (c === "\n") {
      record.push(field);
      rows.push(record);
      record = [];
      field = "";
    } else if (c === "\r") {
      // swallow — handled by the following \n
    } else {
      field += c;
    }
  }
  // trailing field / record (no final newline)
  if (field !== "" || record.length > 0) {
    record.push(field);
    rows.push(record);
  }
  if (rows.length === 0) return [];
  const header = rows[0].map((h, idx) => (idx === 0 ? h.replace(/^﻿/, "") : h).trim());
  return rows.slice(1).map((r) => {
    const obj = {};
    header.forEach((h, idx) => {
      obj[h] = (r[idx] ?? "").trim();
    });
    return obj;
  });
}

function readCsv(name) {
  return parseCsv(readFileSync(join(CSV_DIR, name), "utf-8"));
}

// SQL literal: 'escaped' or NULL when empty/nullish.
function lit(v) {
  if (v === null || v === undefined || v === "") return "NULL";
  return `'${String(v).replace(/'/g, "''")}'`;
}

function header(lines) {
  return lines.join("\n") + "\n\n";
}

// ---------------------------------------------------------------------------
// Markets — Market_Level_1 = parent (parent_id NULL), Market_Level_2 = child.
// ---------------------------------------------------------------------------
function genMarkets() {
  const rows = readCsv("Market_list_CN.csv");
  const l1 = new Map(); // en -> { id, zh }
  const l2 = new Map(); // "l1||l2" -> { id, en, zh, parentId }
  for (const r of rows) {
    const l1en = r["Market_Level_1_EN"];
    const l1zh = r["Market_Level_1_CN"];
    const l2en = r["Market_Level_2_EN"];
    const l2zh = r["Market_Level_2_CN"];
    if (!l1en) continue;
    if (!l1.has(l1en)) l1.set(l1en, { id: id(`market|${l1en}`), zh: l1zh });
    if (l2en) {
      const key = `${l1en}||${l2en}`;
      if (!l2.has(key))
        l2.set(key, {
          id: id(`market|${l1en}|${l2en}`),
          en: l2en,
          zh: l2zh,
          parentId: l1.get(l1en).id,
        });
    }
  }
  const out = [];
  out.push("-- Seed markets from CSV (docs/taxonomy_cn/Market_list_CN.csv): L1 = parent, L2 = child with parent_id.");
  out.push("-- Bilingual: name = English, name_zh = Simplified Chinese. Generated by scripts/generate-taxonomy-seeds.mjs.");
  out.push("DELETE FROM public.company_markets;");
  out.push("DELETE FROM public.markets;");
  out.push("");
  out.push("-- L1 (Market_Level_1)");
  for (const [en, v] of l1) {
    out.push(
      `INSERT INTO public.markets (id, name, name_zh, parent_id, sort_order) VALUES (${lit(v.id)}, ${lit(en)}, ${lit(v.zh)}, NULL, 0);`,
    );
  }
  out.push("");
  out.push("-- L2 (Market_Level_2)");
  for (const [, v] of l2) {
    out.push(
      `INSERT INTO public.markets (id, name, name_zh, parent_id, sort_order) VALUES (${lit(v.id)}, ${lit(v.en)}, ${lit(v.zh)}, ${lit(v.parentId)}, 0);`,
    );
  }
  writeFileSync(join(SEED_DIR, "020_seed_markets.sql"), header(out));
  return { l1: l1.size, l2: l2.size };
}

// ---------------------------------------------------------------------------
// Standards — Industry = L1 (parent NULL), Standard = L2. Chinese label keeps the
// international code and appends the Chinese description: "ISO 9001 质量管理体系".
// ---------------------------------------------------------------------------
function genStandards() {
  const rows = readCsv("standard_taxonomy_CN.csv");
  const l1 = new Map(); // industryEn -> { id, zh }
  const l2 = new Map(); // "industry||standard" -> { id, en, zh, parentId }
  for (const r of rows) {
    const indEn = r["Industry_EN"];
    const indZh = r["Industry_CN"];
    const std = r["Standard"];
    const stdZh = r["Standard_Name_CN"];
    if (!indEn) continue;
    if (!l1.has(indEn)) l1.set(indEn, { id: id(`standard|${indEn}`), zh: indZh });
    if (std) {
      const key = `${indEn}||${std}`;
      if (!l2.has(key))
        l2.set(key, {
          id: id(`standard|${indEn}|${std}`),
          en: std,
          zh: stdZh ? `${std} ${stdZh}` : "",
          parentId: l1.get(indEn).id,
        });
    }
  }
  const out = [];
  out.push("-- Seed standards/certifications from CSV (docs/taxonomy_cn/standard_taxonomy_CN.csv): Industry = L1, Standard = L2.");
  out.push("-- Bilingual: name = English (code), name_zh = \"<code> <Chinese name>\". Generated by scripts/generate-taxonomy-seeds.mjs.");
  out.push("DELETE FROM public.company_standards;");
  out.push("DELETE FROM public.standards_ref;");
  out.push("");
  out.push("-- L1 (Industry)");
  for (const [en, v] of l1) {
    out.push(
      `INSERT INTO public.standards_ref (id, name, name_zh, parent_id, sort_order) VALUES (${lit(v.id)}, ${lit(en)}, ${lit(v.zh)}, NULL, 0);`,
    );
  }
  out.push("");
  out.push("-- L2 (Standard)");
  for (const [, v] of l2) {
    out.push(
      `INSERT INTO public.standards_ref (id, name, name_zh, parent_id, sort_order) VALUES (${lit(v.id)}, ${lit(v.en)}, ${lit(v.zh)}, ${lit(v.parentId)}, 0);`,
    );
  }
  writeFileSync(join(SEED_DIR, "030_seed_standards.sql"), header(out));
  return { l1: l1.size, l2: l2.size };
}

// ---------------------------------------------------------------------------
// Competency — 3-level tree. Matches the existing seed's shape:
//   L1: category = domain (itself),  parent = NULL
//   L2: category = domain (its L1),  parent = L1.id
//   L3: category = NULL,             parent = L2.id
// Then sync competency_taxonomy_seed -> company_capabilities_ref.
// ---------------------------------------------------------------------------
function genCompetency() {
  const rows = readCsv("Competency_Taxonomy_CN.csv");
  const l1 = new Map(); // en -> { id, zh }
  const l2 = new Map(); // "l1||l2" -> { id, en, zh, l1en, l1zh, parentId }
  const l3 = new Map(); // "l1||l2||l3" -> { id, en, zh, parentId }
  for (const r of rows) {
    const d1en = r["Level1_Domain_EN"];
    const d1zh = r["Level1_Domain_CN"];
    const d2en = r["Level2_CapabilityGroup_EN"];
    const d2zh = r["Level2_CapabilityGroup_CN"];
    const d3en = r["Level3_Competency_EN"];
    const d3zh = r["Level3_Competency_CN"];
    if (!d1en) continue;
    if (!l1.has(d1en)) l1.set(d1en, { id: id(`competency|${d1en}`), zh: d1zh });
    if (d2en) {
      const k2 = `${d1en}||${d2en}`;
      if (!l2.has(k2))
        l2.set(k2, {
          id: id(`competency|${d1en}|${d2en}`),
          en: d2en,
          zh: d2zh,
          l1en: d1en,
          l1zh: d1zh,
          parentId: l1.get(d1en).id,
        });
      if (d3en) {
        const k3 = `${d1en}||${d2en}||${d3en}`;
        if (!l3.has(k3))
          l3.set(k3, {
            id: id(`competency|${d1en}|${d2en}|${d3en}`),
            en: d3en,
            zh: d3zh,
            parentId: l2.get(k2).id,
          });
      }
    }
  }
  const cols = "(id, name, name_zh, category, category_zh, parent_id, is_active)";
  const out = [];
  out.push("-- Seed competency taxonomy from CSV (docs/taxonomy_cn/Competency_Taxonomy_CN.csv).");
  out.push("-- Bilingual: name/category = English, name_zh/category_zh = Simplified Chinese.");
  out.push("-- Populates competency_taxonomy_seed and syncs to company_capabilities_ref.");
  out.push("-- Generated by scripts/generate-taxonomy-seeds.mjs.");
  out.push("");
  out.push("-- Full rebuild: IDs are regenerated from the CSV, so clear the working ref");
  out.push("-- table too (cascades to company_capabilities). Company selections are");
  out.push("-- preserved across a reseed by scripts/reseed-taxonomy-with-remap.mjs.");
  out.push("DELETE FROM public.company_capabilities;");
  out.push("DELETE FROM public.company_capabilities_ref;");
  out.push("DELETE FROM public.competency_taxonomy_seed;");
  out.push("");
  out.push("-- L1 (Level1_Domain): category = domain itself");
  for (const [en, v] of l1) {
    out.push(
      `INSERT INTO public.competency_taxonomy_seed ${cols} VALUES (${lit(v.id)}, ${lit(en)}, ${lit(v.zh)}, ${lit(en)}, ${lit(v.zh)}, NULL, true);`,
    );
  }
  out.push("");
  out.push("-- L2 (Level2_CapabilityGroup): category = parent L1 domain");
  for (const [, v] of l2) {
    out.push(
      `INSERT INTO public.competency_taxonomy_seed ${cols} VALUES (${lit(v.id)}, ${lit(v.en)}, ${lit(v.zh)}, ${lit(v.l1en)}, ${lit(v.l1zh)}, ${lit(v.parentId)}, true);`,
    );
  }
  out.push("");
  out.push("-- L3 (Level3_Competency): category = NULL");
  for (const [, v] of l3) {
    out.push(
      `INSERT INTO public.competency_taxonomy_seed ${cols} VALUES (${lit(v.id)}, ${lit(v.en)}, ${lit(v.zh)}, NULL, NULL, ${lit(v.parentId)}, true);`,
    );
  }
  out.push("");
  out.push("-- Sync canonical seed into the working ref table used by companies.");
  out.push("INSERT INTO public.company_capabilities_ref (id, name, name_zh, category, category_zh, parent_id, is_active)");
  out.push("SELECT id, name, name_zh, category, category_zh, parent_id, is_active FROM public.competency_taxonomy_seed");
  out.push("ON CONFLICT (id) DO UPDATE SET name = EXCLUDED.name, name_zh = EXCLUDED.name_zh, category = EXCLUDED.category, category_zh = EXCLUDED.category_zh, parent_id = EXCLUDED.parent_id, is_active = EXCLUDED.is_active;");
  writeFileSync(join(SEED_DIR, "010_seed_competency_taxonomy.sql"), header(out));
  return { l1: l1.size, l2: l2.size, l3: l3.size };
}

const m = genMarkets();
const s = genStandards();
const c = genCompetency();
console.log("Regenerated seed SQL from docs/taxonomy_cn/:");
console.log(`  markets:      ${m.l1} L1 + ${m.l2} L2 = ${m.l1 + m.l2} rows`);
console.log(`  standards:    ${s.l1} L1 + ${s.l2} L2 = ${s.l1 + s.l2} rows`);
console.log(`  competencies: ${c.l1} L1 + ${c.l2} L2 + ${c.l3} L3 = ${c.l1 + c.l2 + c.l3} rows`);
